#!/usr/bin/env node
'use strict';
// Regenerates the site's data files from the engine: style presets and the pre-traced hero drawing.
// Usage: node site/build.js   (needs the engine dependencies: run skills/inkline/scripts/inkline doctor once)
const fs = require('fs');
const path = require('path');
const ENGINE = path.join(__dirname, '..', 'skills', 'inkline', 'engine');
const { listStyles, resolveStyle } = require(path.join(ENGINE, 'src', 'styles'));
const { launch, openComposition } = require(path.join(ENGINE, 'src', 'browser'));
const { traceOnPage } = require(path.join(ENGINE, 'src', 'pipeline'));

(async () => {
  const styles = {};
  for (const s of listStyles().filter((x) => x.source === 'preset')) styles[s.name] = resolveStyle(s.name);
  fs.mkdirSync(path.join(__dirname, 'data'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, 'data', 'styles.js'), `// generated by site/build.js\nwindow.INKLINE_STYLES = ${JSON.stringify(styles)};\n`);

  const { browser } = await launch((m) => process.stderr.write(m + '\n'));
  try {
    const page = await openComposition(browser, 800, 800);
    for (const name of ['pearl']) {
      const project = await traceOnPage(page, path.join(__dirname, 'media', 'sources', `${name}.jpg`), styles.graphite.trace);
      fs.writeFileSync(path.join(__dirname, 'data', `${name}.js`), `// generated by site/build.js from media/sources/${name}.jpg (public domain)\nwindow.INKLINE_DEMO = ${JSON.stringify(project)};\n`);
      process.stdout.write(`${name}: ${project.strokes.length} strokes\n`);
    }
  } finally {
    await browser.close();
  }
})();
